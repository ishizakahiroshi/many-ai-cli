#requires -Version 7.0
[CmdletBinding()]
param([string]$OutputDir = (Join-Path $PSScriptRoot 'fixtures/generated'))
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# Generate synthetic inputs only. No sessions, network, builds, or executable runs.
$scenario = Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot 'scenario.json') | ConvertFrom-Json
if ($scenario.schema_version -ne 1 -or $scenario.seed -ne 42 -or $scenario.limit_bytes -ne 2097152 -or $scenario.fixture_cycles -ne 100 -or ($scenario.chunk_lengths -join ',') -cne '64,64,64,64,64,64,512,512,512,4096') {
    throw 'Unsupported fixture scenario; review both implementations and controller before changing it.'
}
if (Test-Path -LiteralPath $OutputDir) { throw 'Output directory already exists. Choose a new empty destination; existing evidence is never overwritten.' }
$null = New-Item -ItemType Directory -Path $OutputDir
$OutputDir = (Resolve-Path -LiteralPath $OutputDir).Path
$utf8 = [Text.UTF8Encoding]::new($false)
$limit = [int]$scenario.limit_bytes
$script:state = [uint64]$scenario.seed
function Next-U32 {
    $script:state = ($script:state * [uint64]1664525 + [uint64]1013904223) % [uint64]4294967296
    return $script:state
}
function New-Pattern([int]$Count, [byte[]]$Pattern) {
    $data = [byte[]]::new($Count)
    if ($Count -eq 0) { return ,$data }
    if ($Pattern.Length -eq 0) { throw 'Empty source pattern' }
    $filled = [Math]::Min($Count, $Pattern.Length)
    [Buffer]::BlockCopy($Pattern, 0, $data, 0, $filled)
    while ($filled -lt $Count) {
        $take = [Math]::Min($filled, $Count - $filled)
        [Buffer]::BlockCopy($data, 0, $data, $filled, $take)
        $filled += $take
    }
    return ,$data
}
function Split-Chunks([int]$Count, [int]$Size) {
    $parts = [Collections.Generic.List[int]]::new()
    if ($Count -eq 0) { $parts.Add(0) }
    for ($at = 0; $at -lt $Count; $at += $Size) { $parts.Add([Math]::Min($Size, $Count - $at)) }
    return ,$parts.ToArray()
}
function Random-Chunks([int]$Count) {
    $parts = [Collections.Generic.List[int]]::new()
    $at = 0
    while ($at -lt $Count) {
        $take = [Math]::Min(1 + [int]((Next-U32) % 8192), $Count - $at)
        $parts.Add($take)
        $at += $take
    }
    return ,$parts.ToArray()
}
$cases = [Collections.Generic.List[string]]::new()
function Write-Case([string]$Name, [byte[]]$Data, [int[]]$Chunks) {
    $sum = [int64]0
    foreach ($size in $Chunks) { if ($size -lt 0) { throw 'Negative chunk' }; $sum += $size }
    if ($Chunks.Count -eq 0 -or $sum -ne $Data.Length) { throw "Invalid boundaries: $Name" }
    [IO.File]::WriteAllBytes((Join-Path $OutputDir "$Name.bin"), $Data)
    [IO.File]::WriteAllText((Join-Path $OutputDir "$Name.csv"), (($Chunks | ForEach-Object { $_.ToString([Globalization.CultureInfo]::InvariantCulture) }) -join "`n") + "`n", $utf8)
    $cases.Add("$Name`t$Name.bin`t$Name.csv")
}
$pattern = [byte[]](0..250)
foreach ($size in @(0, 1, ($limit - 1), $limit, ($limit + 1), ($limit + 123), (2 * $limit + 17))) {
    Write-Case "boundary-$size" (New-Pattern $size $pattern) @($size)
}
$history = [Text.Encoding]::UTF8.GetBytes("previous conversation`r`n")
$historyData = New-Pattern ($history.Length * 24000) $history
Write-Case 'retains-over-64k' $historyData (Split-Chunks $historyData.Length 4096)
$bounded = New-Pattern ($limit + 32769) $pattern
Write-Case 'bounded-4096' $bounded (Split-Chunks $bounded.Length 4096)
Write-Case 'bounded-large-chunk' $bounded (Split-Chunks $bounded.Length ($limit + 123))
# UTF-8 e6 97 a5 e6 9c ac, ESC[31m, NUL, deliberately incomplete/invalid UTF-8.
$split = [byte[]]@(0, 230, 151, 165, 230, 156, 172, 27, 91, 51, 49, 109, 65, 27, 91, 48, 109, 13, 10, 240, 159, 255, 0)
Write-Case 'split-utf8-ansi-nul' $split (Split-Chunks $split.Length 1)
Write-Case 'snapshot-then-append' (New-Pattern 24 $pattern) @(8, 0, 8, 8)
# LCG specified here rather than System.Random, so generated bytes are reproducible.
$random = [byte[]]::new($limit + 65537)
for ($i = 0; $i -lt $random.Length; $i++) { $random[$i] = [byte]((Next-U32) -shr 24) }
Write-Case 'random-fixed' $random (Split-Chunks $random.Length 4096)
Write-Case 'random-boundaries' $random (Random-Chunks $random.Length)
[IO.File]::WriteAllText((Join-Path $OutputDir 'cases.tsv'), ($cases -join "`n") + "`n", $utf8)
[IO.File]::WriteAllBytes((Join-Path $OutputDir 'prefill.bin'), (New-Pattern $limit $pattern))
# Each ten-chunk cycle preserves 60/30/10 percent counts; shuffle within each cycle.
$chunks = [Collections.Generic.List[int]]::new()
for ($cycle = 0; $cycle -lt [int]$scenario.fixture_cycles; $cycle++) {
    $sizes = [int[]]$scenario.chunk_lengths.Clone()
    for ($i = $sizes.Length - 1; $i -gt 0; $i--) {
        $j = [int]((Next-U32) % ($i + 1))
        $tmp = $sizes[$i]; $sizes[$i] = $sizes[$j]; $sizes[$j] = $tmp
    }
    foreach ($size in $sizes) { $chunks.Add($size) }
}
$bytes = [int]($chunks | Measure-Object -Sum).Sum
[IO.File]::WriteAllBytes((Join-Path $OutputDir 'mixed.bin'), (New-Pattern $bytes $random))
[IO.File]::WriteAllText((Join-Path $OutputDir 'chunks.csv'), (($chunks | ForEach-Object { $_.ToString([Globalization.CultureInfo]::InvariantCulture) }) -join "`n") + "`n", $utf8)
$files = @(Get-ChildItem -LiteralPath $OutputDir -File | Sort-Object Name | ForEach-Object {
    [ordered]@{ name = $_.Name; bytes = $_.Length; sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant() }
})
$manifest = [ordered]@{
    schema_version = 1; seed = [int]$scenario.seed; generator = 'LCG32 1664525*x+1013904223 mod 2^32, high byte';
    cases = $cases.Count; mixed_bytes = $bytes; mixed_chunks = $chunks.Count;
    scenario_sha256 = (Get-FileHash -LiteralPath (Join-Path $PSScriptRoot 'scenario.json') -Algorithm SHA256).Hash.ToLowerInvariant();
    generator_sha256 = (Get-FileHash -LiteralPath $PSCommandPath -Algorithm SHA256).Hash.ToLowerInvariant(); files = $files
}
[IO.File]::WriteAllText((Join-Path $OutputDir 'manifest.json'), ($manifest | ConvertTo-Json -Depth 8) + "`n", $utf8)
Write-Host "Prepared $($cases.Count) synthetic correctness cases and $($chunks.Count) benchmark chunks. No EXE was run."
