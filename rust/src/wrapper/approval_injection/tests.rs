/// The frozen Go text the pinned cases were generated with. Not shipped.
const GO_RULES: &str = include_str!("rules.txt");
#[test]
fn pinned_go_98_marker_injection_removal_and_byte_preservation_cases() {
    #[derive(Deserialize)]
    struct Case {
        #[serde(rename = "Name")]
        name: String,
        #[serde(rename = "Provider")]
        provider: String,
        #[serde(rename = "Body")]
        body: String,
    }
    #[derive(Deserialize)]
    struct Golden {
        #[serde(rename = "Name")]
        name: String,
        #[serde(rename = "Injected")]
        injected: String,
        #[serde(rename = "Removed")]
        removed: String,
        #[serde(rename = "Stripped")]
        stripped: String,
        #[serde(rename = "Error")]
        error: bool,
    }
    let cases: Vec<Case> = serde_json::from_str(include_str!("cases.json")).unwrap();
    let golden: Vec<Golden> = serde_json::from_str(include_str!("golden.json")).unwrap();
    assert_eq!(cases.len(), 98);
    assert_eq!(cases.len(), golden.len());
    for (case, golden) in cases.into_iter().zip(golden) {
        assert_eq!(case.name, golden.name);
        let body = STANDARD.decode(case.body).unwrap();
        assert_eq!(
            strip_blocks(&body),
            STANDARD.decode(golden.stripped).unwrap(),
            "{}",
            case.name
        );
        // The cases were generated by the Go version with its rules (version 25).
        let actual = inject_rules_at(
            &case.provider,
            &body,
            GO_RULES.as_bytes(),
            "<!-- version: 25 -->",
        );
        assert_eq!(actual.is_err(), golden.error, "{}", case.name);
        if let Ok(actual) = actual {
            assert_eq!(
                actual,
                STANDARD.decode(golden.injected).unwrap(),
                "{}",
                case.name
            );
            assert_eq!(
                remove_rules_content(&case.provider, &actual).unwrap(),
                STANDARD.decode(golden.removed).unwrap(),
                "{}",
                case.name
            );
        }
    }
}
