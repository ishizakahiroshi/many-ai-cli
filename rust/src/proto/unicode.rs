//! Go unicode.ToLower scalar mapping from the pinned Go 1.26.8 Unicode table.
//! This preserves source simple casing, including U+0130 -> i, without Rust's
//! expanding lowercase or later Unicode additions changing native path keys.
pub fn simple_lower(value: &str) -> String {
    value
        .chars()
        .map(
            |c| match LOWER.binary_search_by_key(&(c as u32), |pair| pair.0) {
                Ok(index) => char::from_u32(LOWER[index].1).expect("generated scalar mapping"),
                Err(_) => c,
            },
        )
        .collect()
}
