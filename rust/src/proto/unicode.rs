/// Go Unicode 15 SimpleFold equivalence key; scalar-only, no expansions.
pub fn simple_fold_key(value: &str) -> String {
    value
        .chars()
        .map(|c| {
            let n = c as u32;
            let key = SIMPLE_FOLD
                .binary_search_by_key(&n, |&(from, _)| from)
                .map(|i| SIMPLE_FOLD[i].1)
                .unwrap_or(n);
            char::from_u32(key).expect("Go scalar mapping")
        })
        .collect()
}
